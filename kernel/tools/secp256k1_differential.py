#!/usr/bin/env python3
"""Grade the libsecp256k1 differential runner against the Rust reference.

`kernel/differential/vectors/ledger.sighash.differential.txt` is generated by
`zerocoin/tests/differential_vectors.rs`. Every `RUST` line in it is the verdict
of the live Rust implementation, re-derived on each `cargo test` run by
`differential_vectors_match_rust_reference`. This script never computes a
verdict of its own: it only checks that the C++ runner reproduced every one of
them, and that no case was skipped.

Two things are enforced beyond "no mismatches":

* the case count is pinned, so a shrunken fixture cannot look like a pass;
* every mismatch must be listed on the command line as a *known divergence*,
  and every listed divergence must still be a mismatch. That pins the exact set
  of disagreements in both directions: a new divergence fails the gate, and a
  fixed one fails it too until the allowance is removed.

A liveness check closes the loop: the fixture is corrupted once (the first
case's verdict flipped) and the runner must report that case as a mismatch and
exit 1. If it still reports a clean run, the comparison step is dead and this
script fails rather than passing.

Usage:
  python kernel/tools/secp256k1_differential.py \
      --vectors kernel/differential/vectors/ledger.sighash.differential.txt \
      --runner .build/p26-differential/secp256k1_differential.exe \
      --expect-cases 117 --known-divergence V4.prefix_05

Exit codes: 0 the runner reproduced every verdict (within the allowances),
1 a verdict differed or the run was malformed, 2 bad input or a dead comparison.
"""

from __future__ import annotations

import argparse
import re
import subprocess
import sys
import tempfile
from pathlib import Path

CASE_RE = re.compile(
    r"^CASE (?P<id>\S+) group=(?P<group>\S+) "
    r"rust=(?P<rust>accept|reject) seam=(?P<seam>accept|reject) "
    r"backend=(?P<backend>accept|reject) match=(?P<match>yes|no) "
    r"adapter=(?P<adapter>faithful|load-bearing)$"
)
SUMMARY_RE = re.compile(
    r"^SUMMARY cases=(?P<cases>\d+) failures=(?P<failures>\d+) "
    r"adapter_divergences=(?P<adapter>\d+)$"
)


class Dead(Exception):
    """The comparison itself could not be trusted."""


def run_runner(runner: Path, fixture: Path) -> tuple[int, list[str], str]:
    """Run the runner once and return (exit code, stdout lines, stderr)."""
    completed = subprocess.run(
        [str(runner), str(fixture)],
        capture_output=True,
        text=True,
        check=False,
    )
    return completed.returncode, completed.stdout.splitlines(), completed.stderr


def parse(lines: list[str]) -> tuple[list[dict[str, str]], dict[str, int]]:
    cases: list[dict[str, str]] = []
    summary: dict[str, int] | None = None
    for line in lines:
        if line.startswith("CASE "):
            match = CASE_RE.match(line)
            if match is None:
                raise Dead(f"unparsable CASE line: {line}")
            cases.append(match.groupdict())
        elif line.startswith("SUMMARY "):
            summary_match = SUMMARY_RE.match(line)
            if summary_match is None:
                raise Dead(f"unparsable SUMMARY line: {line}")
            summary = {k: int(v) for k, v in summary_match.groupdict().items()}
    if summary is None:
        raise Dead("runner printed no SUMMARY line")
    if not cases:
        raise Dead("runner printed no CASE lines")
    return cases, summary


def liveness_check(
    runner: Path, fixture: Path, cases: list[dict[str, str]], baseline: set[str]
) -> None:
    """Corrupt one recorded verdict and require the runner to notice.

    `baseline` is the mismatch set of the unmodified fixture. Real divergences
    survive into the corrupted copy, so the corruption must add exactly one
    mismatch on top of them rather than replace the set.
    """
    text = fixture.read_text(encoding="utf-8")
    target = cases[0]["id"]
    wanted = "reject" if cases[0]["rust"] == "accept" else "accept"

    output: list[str] = []
    skipping = False
    flipped = False
    for line in text.splitlines():
        if line.startswith(f"CASE {target}"):
            skipping = True
        elif line == "END":
            skipping = False
        elif skipping and line.startswith("RUST ") and not flipped:
            output.append(f"RUST {wanted}")
            flipped = True
            continue
        output.append(line)
    if not flipped:
        raise Dead(f"could not find the RUST line of {target} to corrupt")

    with tempfile.TemporaryDirectory() as scratch:
        corrupted = Path(scratch) / "corrupted.txt"
        corrupted.write_text("\n".join(output) + "\n", encoding="utf-8")
        code, lines, _ = run_runner(runner, corrupted)
        cases_out, _ = parse(lines)

    if code == 0:
        raise Dead(f"corrupting {target} still produced exit 0: the comparison is dead")
    if code != 1:
        raise Dead(f"corrupting {target} produced exit {code}, expected 1")
    flagged = {case["id"] for case in cases_out if case["match"] == "no"}
    if flagged - baseline != {target} or len(flagged) != len(baseline) + 1:
        raise Dead(
            f"corrupting {target} flagged {sorted(flagged)}, "
            f"expected {sorted(baseline)} plus {target}"
        )


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--vectors", required=True, help="differential fixture")
    parser.add_argument("--runner", required=True, help="secp256k1_differential binary")
    parser.add_argument("--expect-cases", type=int, required=True)
    parser.add_argument(
        "--known-divergence",
        action="append",
        default=[],
        metavar="CASE_ID",
        help="a case whose Rust and C++ verdicts disagree on purpose; repeatable",
    )
    parser.add_argument(
        "--no-liveness-check",
        action="store_true",
        help="skip the corrupted-fixture self-check (not for gates)",
    )
    args = parser.parse_args(argv)

    fixture = Path(args.vectors).resolve()
    runner = Path(args.runner).resolve()
    if not fixture.is_file():
        print(f"secp256k1 differential: missing fixture {fixture}", file=sys.stderr)
        return 2
    if not runner.is_file():
        print(f"secp256k1 differential: missing runner {runner}", file=sys.stderr)
        return 2

    known = set(args.known_divergence)

    try:
        code, lines, stderr = run_runner(runner, fixture)
        cases, summary = parse(lines)
        baseline = {case["id"] for case in cases if case["match"] == "no"}
        if not args.no_liveness_check:
            liveness_check(runner, fixture, cases, baseline)
    except Dead as error:
        print(f"secp256k1 differential: DEAD COMPARISON — {error}", file=sys.stderr)
        if "stderr" in locals() and stderr:
            print(stderr, file=sys.stderr)
        return 2

    failures = [case for case in cases if case["match"] == "no"]
    failure_ids = {case["id"] for case in failures}
    unexpected = sorted(failure_ids - known)
    stale = sorted(known - failure_ids)

    if len(cases) != args.expect_cases:
        print(
            f"secp256k1 differential: {len(cases)} cases, expected {args.expect_cases}",
            file=sys.stderr,
        )
        return 1
    if summary["cases"] != len(cases) or summary["failures"] != len(failures):
        print(f"secp256k1 differential: SUMMARY disagrees with the CASE lines: {summary}",
              file=sys.stderr)
        return 1
    if unexpected:
        print("secp256k1 differential: FAIL — undocumented divergence(s):", file=sys.stderr)
        for case in failures:
            if case["id"] in unexpected:
                print(
                    f"  {case['id']}: rust={case['rust']} seam={case['seam']} "
                    f"backend={case['backend']}",
                    file=sys.stderr,
                )
        return 1
    if stale:
        print(
            "secp256k1 differential: FAIL — stale --known-divergence entry: "
            + ", ".join(stale)
            + " now matches; remove the allowance",
            file=sys.stderr,
        )
        return 1
    expected_code = 1 if failures else 0
    if code != expected_code:
        print(
            f"secp256k1 differential: runner exit {code}, expected {expected_code}",
            file=sys.stderr,
        )
        return 1

    groups: dict[str, int] = {}
    for case in cases:
        groups[case["group"]] = groups.get(case["group"], 0) + 1

    accepted = sum(1 for case in cases if case["rust"] == "accept")
    print(
        f"secp256k1 differential: {len(cases) - len(failures)}/{len(cases)} cases match "
        f"the Rust reference ({accepted} accept, {len(cases) - accepted} reject)"
    )
    print("  groups                " + ", ".join(f"{name}={count}" for name, count in sorted(groups.items())))
    for case in cases:
        if case["adapter"] == "load-bearing":
            print(
                f"  adapter load-bearing  {case['id']} "
                f"(rust={case['rust']} backend={case['backend']})"
            )
    if failures:
        print(f"  documented divergence {len(failures)}:")
        for case in failures:
            print(
                f"    {case['id']}: rust={case['rust']} seam={case['seam']} "
                f"backend={case['backend']}"
            )
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
